#!/usr/bin/env python3
"""The decode work gate rejects failed runs and altered complete patterns."""
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

PROJECT = Path(__file__).resolve().parents[4]
sys.path.insert(0, str(PROJECT/'tests/src/pattern'))
import benchmark_primary_decode_calls as benchmark

BIN = Path(sys.argv.pop(1)).resolve() if len(sys.argv) > 1 else PROJECT/'build/icl-pattern-generation'


class DecodeCounterGate(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.folder = tempfile.TemporaryDirectory(prefix='decode-counter-gate-')
        cls.addClassCleanup(cls.folder.cleanup)
        root = Path(cls.folder.name)
        model, commands = benchmark.fixture(256, 'automatic')
        (root/'source.icl').write_text(model)
        (root/'source.pdl').write_text(commands)
        result = subprocess.run([str(BIN), '--icl', 'source.icl', '--pdl', 'source.pdl',
            '--top_module', 'Chains', '--output', 'result.pdl'], cwd=root,
            capture_output=True, text=True, timeout=60)
        if result.returncode:
            raise RuntimeError(result.stdout+result.stderr)
        cls.pattern = root/'result.pdl'
        cls.data = cls.pattern.read_bytes()

    def check_result(self, status, data, stderr):
        # Inject process failures at the boundary; validate real generated bytes.
        original_run = benchmark.subprocess.run
        original_output = benchmark.subprocess.check_output
        try:
            benchmark.subprocess.check_output = lambda *a, **k: 'c++ -o build/icl-pattern-generation\n'
            def run(command, **kwargs):
                if '--icl' in command:
                    (Path(kwargs['cwd'])/'result.pdl').write_bytes(data)
                    return subprocess.CompletedProcess(command, status, '', stderr)
                return subprocess.CompletedProcess(command, 0, '', '')
            benchmark.subprocess.run = run
            return benchmark.measure()
        finally:
            benchmark.subprocess.run = original_run
            benchmark.subprocess.check_output = original_output

    def test_accepts_qualified_output(self):
        row = self.check_result(0, self.data, 'model_eval_calls=471064\n')
        self.assertEqual(row['model_eval_calls'], 471064)
        self.assertEqual(row['apply_count'], 1028)
        self.assertEqual(row['callback_postconditions'], 1024)

    def test_rejects_altered_complete_output(self):
        lines = self.data.splitlines(keepends=True)
        moved = b''.join(line for line in lines if not line.startswith(b'iState '))
        moved += b''.join(line for line in lines if line.startswith(b'iState '))
        for data in (moved, self.data+b'iApply\n'):
            with self.subTest(extra_apply=data.endswith(b'iApply\n')):
                with self.assertRaisesRegex(RuntimeError, 'complete output differs'):
                    self.check_result(0, data, 'model_eval_calls=471064\n')

    def test_rejects_work_and_process_failures_with_optimization(self):
        script = Path(__file__).resolve()
        code = ('import importlib.util, pathlib, sys; '
                'sys.argv=[sys.argv[1],sys.argv[2]]; '
                's=importlib.util.spec_from_file_location("gate",sys.argv[0]); '
                'm=importlib.util.module_from_spec(s);s.loader.exec_module(m); '
                'm.DecodeCounterGate().check_result(STATUS, pathlib.Path(PATTERN).read_bytes(), STDERR)')
        for status, stderr, message in [(0, 'model_eval_calls=997408\n', 'work budget'),
            (0, 'model_eval_calls=0\n', 'work budget'), (0, '', 'counter record'),
            (2, 'model_eval_calls=471064\n', 'generator failed')]:
            with self.subTest(status=status, stderr=stderr):
                current = code.replace('STATUS', repr(status)).replace('PATTERN', repr(str(self.pattern))).replace('STDERR', repr(stderr))
                result = subprocess.run([sys.executable, '-O', '-c', current, str(script), str(BIN)],
                    capture_output=True, text=True)
                self.assertNotEqual(result.returncode, 0)
                self.assertIn(message, result.stderr)


if __name__ == '__main__':
    unittest.main()
